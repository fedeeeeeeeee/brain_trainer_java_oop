package controller;

import com.google.common.collect.ImmutableList;

import javafx.application.Platform;
import javafx.fxml.FXML;
import javafx.scene.control.Button;
import javafx.scene.control.Label;
import timer.AgentTimer;
import timer.EventTimer;
import timer.GameTimer;
import timer.GameTimerImpl;
import view.controllers.MiniGameController;

/**
 * The Controller related to the main.fxml GUI.
 *
 */
public final class UIController implements MiniGameController {
    @FXML
    private Label lbl;

    @FXML
    private Button btn;
    
    private AgentTimer agentTimer = new AgentTimer(this); // !!!!!! importante questo passaggio

    /**
     * The handler for the click event generated by the 'btn' button.
     * @throws InterruptedException 
     */
    @FXML
    public void btnOnClickHandler() throws InterruptedException {
    	this.agentTimer.setTime(30);
    	this.agentTimer.start();
//        lbl.setText(elements.stream().collect(Collectors.joining("")));
        
    }

	@Override
	public void updateTimerView(EventTimer eventTimer) {
		 Platform.runLater(() -> this.lbl.setText(Integer.toString(eventTimer.getValue())));
		  if (eventTimer.getValue() == 0) {
			  Platform.runLater(() -> {
				  System.out.println("GAME OVER Time is up");
				  this.agentTimer.stopTimer();
				  System.exit(0); 
			  });
		  }
		
	}
}
